"""Regenerates lib/i18n/{app_strings,strings_en,strings_zh}.dart from tools/i18n_table.py.
Run from the project root:  python3 tools/gen_i18n.py
To add or change a string, edit tools/i18n_table.py (one line per string: key, English, Chinese, params)."""
import sys, re, pathlib
HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from i18n_table import T
OUT = HERE.parent / 'lib' / 'i18n'

def dq(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n') + '"'
# NOTE: templates contain intentional Dart interpolation ($x, ${...}); only quotes/newlines are escaped.

HEADER = '// GENERATED by tools/gen_i18n.py from tools/i18n_table.py — edit the table, not this file.\n'

# ---- abstract class ----
a = [HEADER, "// ignore_for_file: unnecessary_string_interpolations\n\nabstract class AppStrings {\n  const AppStrings();\n"]
for key, en, zh, params in T:
    a.append(f"  String {'get ' + key if not params else key + '(' + params + ')'};\n")
a.append("}\n")
(OUT / 'app_strings.dart').write_text(''.join(a))

def impl(cls, idx, fname):
    o = [HEADER, "// ignore_for_file: unnecessary_string_interpolations, unnecessary_brace_in_string_interps\n\nimport 'app_strings.dart';\n\n", f"class {cls} extends AppStrings {{\n  const {cls}();\n"]
    for row in T:
        key, params = row[0], row[3]
        text = row[idx]
        sig = f"String get {key}" if not params else f"String {key}({params})"
        o.append(f"\n  @override\n  {sig} => {dq(text)};\n")
    o.append("}\n")
    (OUT / fname).write_text(''.join(o))
impl('EnStrings', 1, 'strings_en.dart')
impl('ZhStrings', 2, 'strings_zh.dart')

# ---- sanity: every $placeholder / ${...} variable used is a declared parameter, in BOTH languages ----
bad = []
for key, en, zh, params in T:
    declared = set(re.findall(r'(\w+)\s*(?:,|$)', params.replace('String?', '').replace('String', '').replace('Object', '').replace('int', '').replace('bool', ''))) if params else set()
    for lang, text in (('en', en), ('zh', zh)):
        used = set(re.findall(r'\$([A-Za-z_][A-Za-z0-9_]*)', text)) | set(re.findall(r'\$\{([A-Za-z_][A-Za-z0-9_]*)', text))
        if used - declared: bad.append((key, lang, 'undeclared', used - declared))
        if declared - used and not (key in ('insightOverall',)): bad.append((key, lang, 'unused-param', declared - used))
print('placeholder problems:', bad or 'none')
print('generated', len(T), 'entries')
